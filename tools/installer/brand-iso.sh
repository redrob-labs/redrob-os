#!/usr/bin/bash
# brand-iso.sh -- put the Redrob branding into the installer ISO.
# Copyright 2026 Janghoon Lee (Redrob) and contributors. Apache-2.0.
#
# Why: bootc-image-builder `--type anaconda-iso` assembles the installer's own
# root filesystem from Fedora packages (fedora-logos, Fedora os-release), not
# from our image, so everything under image/branding/usr/share/anaconda and
# image/installer/etc/anaconda is absent while Anaconda runs (v0.3.0 QEMU
# install: Fedora sidebar art, "Welcome to Fedora Linux 44").
#
# How: Anaconda's documented product.img. Its dracut stage looks for
# images/product.img on the stage2 media and overlays it onto the installer
# root before switch-root. We build one from the files already in this repo
# (pixmaps + CSS generated by tools/branding/make_assets.py, the Anaconda
# profile, os-release) and add it to the ISO with xorriso, keeping the boot
# records, then re-implant the media checksum ("Test this media").
#
# usage: tools/installer/brand-iso.sh <in.iso> <out.iso> [fonts-dir]
# needs: cpio, gzip, xorriso, implantisomd5 (isomd5sum)
set -euo pipefail

in="${1:?input iso}"
out="${2:?output iso}"
repo="$(cd "$(dirname "$0")/../.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT
root="${work}/product"

# Installer pixmaps: the Fedora theme CSS references these exact names, so
# replacing the files rebrands the stock layout; our CSS then recolours the
# controls (custom_stylesheet below).
install -d "${root}/usr/share/anaconda/pixmaps"
for f in sidebar-bg.png sidebar-logo.png topbar-bg.png redrob-os.css; do
  install -m 0644 "${repo}/image/branding/usr/share/anaconda/pixmaps/${f}" "${root}/usr/share/anaconda/pixmaps/${f}"
done

# Our os-release: the live environment's boot banner and Anaconda's profile
# detection (os_id = redrob-os) both read it. ID_LIKE=fedora keeps Fedora
# defaults reachable; the profile inherits fedora-kinoite.
install -d "${root}/usr/lib" "${root}/etc"
install -m 0644 "${repo}/image/branding/usr/lib/os-release" "${root}/usr/lib/os-release"
ln -sf ../usr/lib/os-release "${root}/etc/os-release"

install -d "${root}/etc/anaconda/profile.d" "${root}/etc/anaconda/conf.d"
install -m 0644 "${repo}/image/installer/etc/anaconda/profile.d/redrob-os.conf" \
  "${root}/etc/anaconda/profile.d/redrob-os.conf"
# conf.d is read whatever profile is detected, so the stylesheet applies even
# if detection ever falls back to the Fedora profile.
cat > "${root}/etc/anaconda/conf.d/90-redrob-os.conf" <<'EOF'
# Redrob OS installer branding (tools/installer/brand-iso.sh).
[User Interface]
custom_stylesheet = /usr/share/anaconda/pixmaps/redrob-os.css
EOF

# The Plymouth / boot-menu pixmap Anaconda's live environment falls back to.
install -d "${root}/usr/share/pixmaps"
install -m 0644 "${repo}/image/branding/usr/share/pixmaps/system-logo-white.png" "${root}/usr/share/pixmaps/system-logo-white.png"

# Typefaces (optional 3rd argument): the design system's Pretendard + Wanted
# Sans as installed in the OS image (/usr/share/fonts/redrob), plus the same
# fontconfig rule, so the installer's GTK text uses the token font stack too.
fonts="${3:-}"
if [ -n "${fonts}" ]; then
  [ -d "${fonts}" ] || { echo "fonts dir not found: ${fonts}" >&2; exit 1; }
  install -d "${root}/usr/share/fonts/redrob" "${root}/etc/fonts/conf.d"
  cp -r "${fonts}/." "${root}/usr/share/fonts/redrob/"
  install -m 0644 "${repo}/image/files/etc/fonts/conf.d/50-redrob.conf" "${root}/etc/fonts/conf.d/50-redrob.conf"
fi

(cd "${root}" && find . -mindepth 1 | LC_ALL=C sort | cpio --quiet -o -H newc -R 0:0) | gzip -9 > "${work}/product.img"
echo "product.img: $(stat -c %s "${work}/product.img") bytes"
(cd "${root}" && find . -type f -o -type l | LC_ALL=C sort)

rm -f "${out}"
xorriso -indev "${in}" -outdev "${out}" \
  -boot_image any replay \
  -map "${work}/product.img" /images/product.img \
  -end 2>&1 | grep -v '^xorriso : UPDATE' || true
[ -s "${out}" ] || { echo "xorriso produced no output" >&2; exit 1; }
xorriso -indev "${out}" -find /images/product.img -exec report_lba -- 2>/dev/null | grep -q product.img \
  || { echo "product.img missing from ${out}" >&2; exit 1; }
implantisomd5 --force "${out}" >/dev/null
echo "branded: ${out}"
